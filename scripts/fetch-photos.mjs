#!/usr/bin/env node
/**
 * Pulls one free-licence photo per story from Wikimedia Commons, resizes it, and
 * records the credit. Run on your PC (needs internet):
 *
 *   node scripts/fetch-photos.mjs            # fetch missing photos
 *   node scripts/fetch-photos.mjs --force    # refetch all
 *   node scripts/fetch-photos.mjs --only gedi-ruins
 *   node scripts/fetch-photos.mjs --map-only # just regenerate src/lib/storyImages.ts
 *
 * Writes assets/stories/images/<slug>.webp, updates imageCredit in kenya.json and
 * regenerates src/lib/storyImages.ts. Review the photos afterwards: a few places
 * will get a map or a poor shot. Replace the .webp by hand and rerun --map-only.
 */
import { Buffer } from 'node:buffer';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const storiesPath = join(root, 'assets/stories/kenya.json');
const imagesDir = join(root, 'assets/stories/images');
const mapPath = join(root, 'src/lib/storyImages.ts');
const UA = 'SafiriTrips/1.0 (https://nesturex.com; hello@nesturex.com) photo-fetch';
const args = process.argv.slice(2);
const force = args.includes('--force');
const mapOnly = args.includes('--map-only');
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;
const out = (s) => process.stdout.write(`${s}\n`);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

mkdirSync(imagesDir, { recursive: true });
const stories = JSON.parse(readFileSync(storiesPath, 'utf8'));

function writeMap() {
  const files = readdirSync(imagesDir).filter((f) => f.endsWith('.webp'));
  const lines = files
    .map((f) => f.replace(/\.webp$/, ''))
    .filter((slug) => stories.some((s) => s.slug === slug))
    .sort()
    .map((slug) => `  '${slug}': require('../../assets/stories/images/${slug}.webp'),`);
  writeFileSync(
    mapPath,
    `/**\n * Generated by scripts/fetch-photos.mjs. Do not edit by hand.\n * Maps a story slug to a bundled photo.\n */\n/* eslint-disable @typescript-eslint/no-require-imports */\nexport const STORY_IMAGES: Record<string, number> = {\n${lines.join('\n')}\n};\n`,
  );
  out(`storyImages.ts: ${lines.length} photos mapped`);
}

if (mapOnly) {
  writeMap();
  process.exit(0);
}

let sharp;
try {
  sharp = (await import('sharp')).default;
} catch {
  out('The sharp package is missing. Run: npm install --save-dev sharp');
  process.exit(1);
}

async function getJson(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/json' } });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

async function wikiSummary(title) {
  return getJson(
    `https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title.replaceAll(' ', '_'))}`,
  );
}

async function findArticle(story) {
  try {
    const s = await wikiSummary(story.name);
    if (s.type !== 'disambiguation' && s.originalimage) return s;
  } catch {
    /* fall through to geosearch */
  }
  const g = await getJson(
    `https://en.wikipedia.org/w/api.php?action=query&list=geosearch&gscoord=${story.lat}%7C${story.lng}&gsradius=5000&gslimit=5&format=json`,
  );
  for (const hit of g.query?.geosearch ?? []) {
    try {
      const s = await wikiSummary(hit.title);
      if (s.originalimage) return s;
    } catch {
      /* try the next hit */
    }
  }
  return null;
}

const OK_LICENCE = /^(cc0|cc by(-sa)?( \d(\.\d)?)?|public domain|pd)/i;
const stripHtml = (s) =>
  (s ?? '')
    .replace(/<[^>]+>/g, '')
    .replace(/\s+/g, ' ')
    .trim();

async function commonsInfo(imageUrl) {
  const m = /\/wikipedia\/commons\/[0-9a-f]\/[0-9a-f]{2}\/([^/]+)$/.exec(imageUrl);
  if (!m) return { reject: 'image is not on Wikimedia Commons' };
  const file = decodeURIComponent(m[1]);
  const data = await getJson(
    `https://commons.wikimedia.org/w/api.php?action=query&titles=File:${encodeURIComponent(file)}&prop=imageinfo&iiprop=url|extmetadata&iiurlwidth=1400&format=json`,
  );
  const page = Object.values(data.query?.pages ?? {})[0];
  const info = page?.imageinfo?.[0];
  if (!info) return { reject: 'no image info on Commons' };
  const meta = info.extmetadata ?? {};
  const licence = stripHtml(meta.LicenseShortName?.value);
  if (!OK_LICENCE.test(licence) || /nc|nd/i.test(licence)) {
    return { reject: `licence not usable: ${licence || 'unknown'}` };
  }
  const artist = stripHtml(meta.Artist?.value) || stripHtml(meta.Credit?.value) || 'Unknown author';
  return {
    file,
    url: info.thumburl ?? info.url,
    credit: `Photo: ${artist} · ${licence} · commons.wikimedia.org/wiki/File:${file.replaceAll(' ', '_')}`,
  };
}

let done = 0;
let skipped = 0;
for (const story of stories) {
  if (only && story.slug !== only) continue;
  const target = join(imagesDir, `${story.slug}.webp`);
  if (!force && existsSync(target)) {
    done += 1;
    continue;
  }
  try {
    const article = await findArticle(story);
    if (!article) {
      skipped += 1;
      out(`SKIP ${story.slug}: no Wikipedia article with a photo nearby`);
      continue;
    }
    const info = await commonsInfo(article.originalimage.source);
    if (info.reject) {
      skipped += 1;
      out(`SKIP ${story.slug}: ${info.reject} (${article.title})`);
      continue;
    }
    const res = await fetch(info.url, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error(`download HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    await sharp(buf)
      .rotate()
      .resize({ width: 900, withoutEnlargement: true })
      .webp({ quality: 78 })
      .toFile(target);
    story.imageCredit = info.credit;
    done += 1;
    out(`OK   ${story.slug}: ${article.title} (${info.file})`);
  } catch (e) {
    skipped += 1;
    out(`FAIL ${story.slug}: ${e instanceof Error ? e.message : String(e)}`);
  }
  await sleep(400);
}

writeFileSync(storiesPath, `${JSON.stringify(stories, null, 2)}\n`);
writeMap();
out(
  `\n${done} photos in place, ${skipped} to sort out by hand. Open assets/stories/images and check them.`,
);
